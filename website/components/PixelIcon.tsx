type PixelGlyph = keyof typeof glyphs;

function isPixelGlyph(glyph: string): glyph is PixelGlyph {
  return Object.prototype.hasOwnProperty.call(glyphs, glyph);
}

export default function PixelIcon({glyph}: {glyph: string}) {
  if (!isPixelGlyph(glyph)) throw new Error(`Missing skill icon: ${glyph}`);
  const rows = glyphs[glyph].split("\n");
  if (rows.length !== 10 || rows.some(row => !/^[.#]{10}$/.test(row))) {
    throw new Error(`Invalid 10×10 skill icon: ${glyph}`);
  }
  const path = rows.flatMap((row, y) => [...row].map((pixel, x) => pixel === "#" ? `M${x} ${y}h1v1h-1z` : "")).join("");
  return <svg viewBox="0 0 10 10" aria-hidden="true" shapeRendering="crispEdges">
    <path d={path} fill="currentColor"/>
  </svg>;
}
