type PixelGlyph = keyof typeof glyphs;

function isPixelGlyph(glyph: string): glyph is PixelGlyph {
  return Object.prototype.hasOwnProperty.call(glyphs, glyph);
}

export default function PixelIcon({glyph}: {glyph: string}) {
  if (!isPixelGlyph(glyph)) throw new Error(`Missing skill icon: ${glyph}`);
  const rows = glyphs[glyph].split("\n");
  if (rows.length !== 12 || rows.some(row => !/^[.#+]{12}$/.test(row))) {
    throw new Error(`Invalid 12×12 skill icon: ${glyph}`);
  }
  const paths = {"#": "", "+": ""};
  rows.forEach((row, y) => [...row].forEach((pixel, x) => {
    if (pixel === "#" || pixel === "+") paths[pixel] += `M${x} ${y}h1v1h-1z`;
  }));
  return <svg viewBox="0 0 12 12" aria-hidden="true" shapeRendering="crispEdges">
    <path d={paths["#"]} fill="currentColor"/>
    {paths["+"] && <path d={paths["+"]} fill="var(--ink)"/>}
  </svg>;
}
